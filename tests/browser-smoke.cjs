module.exports = async (page, assert, lang) => {
  const text = 'Hello 中文 🌊 + / =\n';
  const encoded = Buffer.from(text).toString('base64');
  await page.fill('#text-input', text);
  await page.waitForFunction(expected => document.querySelector('#text-output').value === expected, encoded);
  assert.match(await page.textContent('#text-status'), lang === 'en' ? /Encoded/ : /编码/);
  await page.click('[data-dir="decode"]');
  await page.fill('#text-input', encoded);
  await page.waitForFunction(expected => document.querySelector('#text-output').value === expected, text);
  await page.fill('#text-input', 'data:text/plain;charset=utf-8;base64,' + encoded.slice(0,8) + '\n' + encoded.slice(8));
  await page.waitForFunction(() => document.querySelector('#text-status').classList.contains('status-success'));
  assert.equal(await page.inputValue('#text-output'), text);
  await page.fill('#text-input', '%%%');
  await page.waitForSelector('#text-status.status-error');
  assert.equal(await page.inputValue('#text-output'), '');
  await page.fill('#text-input', '');
  await page.waitForFunction(() => document.querySelector('#text-status').className === 'status-bar');
  await page.click('[data-tab="image"]');
  const name = '<svg onload="window.syntheticPayload=1">.txt';
  await page.setInputFiles('#file-input', {name, mimeType:'text/plain', buffer:Buffer.from('safe synthetic test')});
  await page.waitForFunction(() => document.querySelector('#b64-output').value.length > 0);
  assert.equal(await page.locator('#file-preview svg').count(), 0);
  assert.equal(await page.evaluate(() => window.syntheticPayload), undefined);
  assert.match(await page.textContent('#file-preview'), /<svg onload=/);
  assert.equal(await page.inputValue('#b64-output'), Buffer.from('safe synthetic test').toString('base64'));
  await page.fill('#b64-input', 'data:text/plain;charset=utf-8;base64,SGVs\nbG8=');
  await page.fill('#decode-filename', 'decoded');
  const download = page.waitForEvent('download');
  await page.click('[onclick="decodeB64()"]');
  const file = await download;
  assert.equal(file.suggestedFilename(), 'decoded.txt');
  const chunks=[]; for await (const c of await file.createReadStream()) chunks.push(c);
  assert.equal(Buffer.concat(chunks).toString(), 'Hello');
};
